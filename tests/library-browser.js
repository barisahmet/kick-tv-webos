window.runLibraryTests = function (assert) {
  var service = serviceGet, originalPlay = playVod, originalAttach = attachVod, requests = [], played = [];
  serviceGet = function (path, cb) { var r = { path: path, cb: cb }; requests.push(r); return { cancel: function () { r.cancelled = true; } }; };
  playVod = function (v, queue, index, slug) { played.push({ v: v, slug: slug }); };
  var item = { id: 'recording', source: 'https://fixture.test/video.m3u8', session_title: 'Recovered video', duration: 1000000, created_at: new Date().toISOString() };
  try {
    openWhatToWatch('suggested');
    requests.splice(0).forEach(function (r) { r.cb('timeout'); });
    var text = document.getElementById('wtw-list').textContent;
    assert(/could not/i.test(text) && /retry/i.test(text) && !/no past videos/i.test(text), 'failed recommendations show an actionable connection error instead of an empty catalogue');
    wtwKey(KEY.OK);
    assert(requests.length === 2, 'remote OK retries recommendation requests');
    requests.splice(0).forEach(function (r) { r.cb(null, []); });
    assert(/no past videos/i.test(document.getElementById('wtw-list').textContent), 'a successful empty response has a distinct empty state');
    wtwSelect('suggested');
    var partial = requests.splice(0); partial[0].cb(null, [item]); partial[1].cb(503);
    assert(wtw.items.some(function (r) { return r.v; }) && /retry/i.test(document.getElementById('wtw-list').textContent), 'partial recommendation failures preserve available videos and offer retry');
    closeWhatToWatch();
    var progress = { version: 1, items: {} };
    for (var i = 0; i < 8; i++) progress.items['alpha:resume-' + i] = { position: 120, duration: 1000, updated: i, title: 'Resume ' + i };
    writeVodProgress(progress);
    openWhatToWatch();
    assert(wtw.mode === 'suggested', 'What to watch opens For you even with unfinished recordings');
    requests = [];
    wtwSelect('resume');
    assert(wtw.mode === 'resume' && wtw.items.length === 8 && state.current === 'alpha', 'all unfinished videos are accessible while live playback continues');
    assert(document.querySelectorAll('#wtw-list .wtw-row').length === 8, 'the resume panel renders more than the four home cards');
    wtwKey(KEY.YELLOW);
    assert(wtw.items.length === 8 && listResumableVods(100).length === 8, 'Yellow does not remove a recording');
    document.querySelector('#wtw-list .wtw-remove').click();
    assert(wtw.items.length === 7 && listResumableVods(100).length === 7, 'Remove button hides one entry from both resume lists');
    assert(savedVodPosition('alpha:resume-7') === 120, 'removing a card preserves its playback position');
    closeWhatToWatch(); openWhatToWatch('resume');
    assert(wtw.items.length === 7, 'dismissed entries stay removed after reopening');
    wtwActivate(); var request = requests.pop();
    closeWhatToWatch(); request.cb(null, [item]);
    assert(played.length === 0, 'closing the library prevents a late video lookup from interrupting live playback');
    openWhatToWatch('resume'); wtwActivate();
    requests.pop().cb('timeout');
    assert(state.current === 'alpha' && /could not/i.test(document.getElementById('wtw-status').textContent), 'failed resume lookup keeps the current stream and displays a retryable error');
    wtwActivate(); requests.pop().cb(null, [Object.assign({}, item, { id: 'resume-6' })]);
    assert(played.length === 1 && played[0].v.id === 'resume-6' && !wtw.open, 'choosing a saved video resolves a fresh URL and starts that recording');
    playVod = originalPlay; attachVod = function () {};
    var video = document.getElementById('video');
    Object.defineProperty(video, 'currentTime', { configurable: true, writable: true, value: 220 });
    Object.defineProperty(video, 'duration', { configurable: true, value: 1000 });
    state.current = null; state.vod = { key: 'alpha:resume-5', slug: 'alpha', progressReady: true, name: 'Alpha', title: 'Resume 5' };
    openWhatToWatch('resume'); wtw.focus = wtw.items.map(function (r) { return r.id; }).indexOf('resume-5');
    document.querySelectorAll('#wtw-list .wtw-remove')[wtw.focus].click();
    video.currentTime = 230; saveVodProgress(true);
    assert(!listResumableVods(Infinity).some(function (r) { return r.id === 'resume-5'; }) && savedVodPosition('alpha:resume-5') === 230, 'ongoing playback keeps its progress without resurrecting a dismissed card');
    closeWhatToWatch();
    playVod(Object.assign({}, item, { id: 'resume-5' }), null, 0, 'alpha');
    assert(state.vod.resumeAt === 230 && listResumableVods(Infinity).some(function (r) { return r.id === 'resume-5'; }), 'explicitly watching a dismissed video restores its card and saved position');
    delete video.currentTime; delete video.duration;
  } finally { closeWhatToWatch(); serviceGet = service; playVod = originalPlay; attachVod = originalAttach; }
};
